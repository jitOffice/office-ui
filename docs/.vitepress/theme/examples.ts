/**
 * 组件文档页里可运行的示例（04 §3）。
 *
 * 为什么是**独立文件**而不是直接写进 md：`component-docs.ts` 会重新生成
 * `docs/components/api/*.md`（`--check` 守着新鲜度），手写进生成物的示例下一次 `docs:gen` 就没了。
 * 放在这里，生成器只负责插一个 `<OjPlayground>`，代码本身有唯一出处。
 *
 * 每个示例都是**组件选项对象**：`playground/index.html` 的沙箱就是
 * `new Function('Vue', 'OfficeUI', 'return (代码)')` 求值这个字面量，所以 `Vue` / `OfficeUI`
 * 在作用域里可用，模板由含编译器的全局构建编译（02 §4.1 的同一条契约）。
 *
 * 四条写示例的规矩，都是踩过的坑：
 * 1. **必须 `components: { OjIcon: OfficeUI.OjIcon }`**：沙箱只 `createApp`，没有全局注册，
 *    直接写 `<oj-icon>` 会被当成未知元素渲染成空标签，看着像"组件坏了"。
 * 2. **不用 `h()`**：示例是给人抄的，模板字符串才是使用者能直接搬走的那一版。
 * 3. **props 用 kebab-case**（`confirm-label`），双向绑定显式写 `@update:model-value`。
 * 4. **数据一律内联字面量**：示例不引外部文件，复制到任何无构建器页面都能跑。
 *
 * 覆盖情况：57 个组件全部有示例。需要宿主上下文的那批（`OjCommandButton` 的命令源、
 * `OjLocaleProvider` 的 i18n 实例、`OjReviewPanel` / `OjCommentThread` / `OjShareDialog` /
 * `OjDockPanel` 的数据结构）在示例里就地造一份最小实现。注意**沙箱的全局 `OfficeUI` 只挂
 * Vue 层**（`src/vue/index.ts` 的导出），所以 `addReply` / `createShareState` / `createDockState`
 * 这类工具函数在示例里手写等价逻辑并注明真实出处；`useLocale` 在 Vue 层上，可以直接用。
 * 照抄进项目就能跑——这也是它们能当"示例"而不是"演示"的原因。
 *
 * 契约由 `docs/test/examples.test.ts` 钉住：能求值、setup() 能跑、模板里的 `oj-*` 都已注册、
 * 键与页面引用一一对应。加示例后忘了 `pnpm docs:gen` 会被它拦下。
 */
